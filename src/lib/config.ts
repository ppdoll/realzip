/** 매매 조회 창(window) — 최근 36개월 = 3년 */
export const WINDOW_MONTHS = 36;

/**
 * 전월세 조회 창 — 최근 12개월 = 1년.
 *
 * 전월세는 매매보다 신고량이 5배 가까이 많다(강남구 3년 69,026행 vs 10,488행).
 * 3년치를 전국으로 담으면 Supabase 무료 티어 500MB 를 훌쩍 넘고, 전세 시세는
 * 계약 갱신 주기(2년)를 감안해도 1년이면 판단에 충분하다.
 */
export const RENT_WINDOW_MONTHS = 12;

/**
 * 월세만 따로 더 짧게 보관한다 — 최근 3개월.
 *
 * 전월세 표의 **48.2%가 월세**인데(실측 604,397행 중 291,097행),
 * 이 앱의 차별점인 전세가율은 전세만 쓴다. 그래서 월세를 짧게 잡으면
 * 전세가율 커버리지를 하나도 잃지 않고 용량을 크게 던다:
 *   전세 12 · 월세 12 -> 519MB (103.8%, 무료 티어 초과)
 *   전세 12 · 월세  3 -> 422MB (84.4%)
 * 전세 창을 대신 줄이면 커버리지가 깎인다 (9개월 -5%, 6개월 -16% 실측).
 *
 * 월세는 "지금 이 단지 월세가 얼마쯤" 을 보는 용도라 3개월이면 충분하다.
 * 화면에서 건수를 적을 때 전세와 기간이 다르다는 것을 밝혀야 한다.
 */
export const MONTHLY_RENT_WINDOW_MONTHS = 3;

/**
 * 국토부 API 동시 호출 수.
 * 6 으로 36개월을 몰아 받으면 실제로 HTTP 429(속도 제한)를 맞는다 — 4 로 낮췄다.
 * 그래도 36개월 수집이 10초대에 끝난다.
 */
export const FETCH_CONCURRENCY = 4;

/** 검색 결과 단지 최대 개수 */
export const MAX_COMPLEXES = 400;
